// ===========================================================================
// 光の加減の設定
//
//   夜景の明るさ・にじみ・雲・空など、見た目の「光」に関わる数値はすべてここに
//   まとめています。値を変えて保存すると、開発サーバー(npm run dev)では
//   シーンが作り直されてすぐに反映されます。
//
//   明るさの値について:
//     シェーダー内の色は「リニア」(物理的な光の量)で扱っています。
//     0 = 真っ黒、1 = 画面で表示できる最大の白。1 を超えた分は
//     トーンマッピングが無効なら白く飛び、ブルームのにじみの元になります。
// ===========================================================================

export const LIGHTING = {
  // -------------------------------------------------------------------------
  // 全体の露出
  // -------------------------------------------------------------------------
  output: {
    // トーンマッピング:明るすぎる部分を白飛びさせず、なだらかに収める処理
    //   'none'    … 無効(1 を超えた部分はそのまま白く飛ぶ。いまの見た目)
    //   'aces'    … 映画的。コントラスト強め、ハイライトがやや黄色寄り
    //   'agx'     … 自然な色味のまま、ハイライトを柔らかく収める
    //   'neutral' … 色相をほぼ変えずに収める
    toneMapping: "none",
    // 露出(全体の明るさの倍率)。トーンマッピングが 'none' 以外のときだけ効く
    exposure: 1.0,
  },

  // -------------------------------------------------------------------------
  // 地面(写真そのもの)
  //   処理後の明るさ = (c * linearGain + c² * highlightGain) * gain
  //   ※ c は写真の明るさから blackLevel を引いた値
  //   highlightGain を上げるほど「明るい所だけ」が強調され、コントラストが増す
  // -------------------------------------------------------------------------
  ground: {
    blackLevel: 0.012, // これ以下の暗さは真っ黒にする(写真のかすみ・ノイズを消す)
    linearGain: 0.7, // 明るさに比例して効く倍率(暗部〜中間の明るさ)
    highlightGain: 1.2, // 明るさの2乗で効く倍率(明るい街明かりほど強く効く)
    gain: 1.0, // 最終的な全体倍率
    edgeFade: 0.08, // 写真の端をぼかして消す幅(写真の幅に対する割合)
  },

  // -------------------------------------------------------------------------
  // 光の粒(写真の明るい画素を抜き出して、立体的に浮かせたもの)
  //   地面の上に「加算」で重なるので、地面の光にさらに上乗せされる
  // -------------------------------------------------------------------------
  points: {
    // ▼ 抜き出しの条件(写真の読み込み時に一度だけ使う)
    sampleStep: 3, // 写真を何ピクセルおきに調べるか(小さいほど粒が細かく多い)
    maxCount: 180000, // 粒の最大数(多いほど密だが重くなる)
    minLuminance: 0.12, // この明るさ未満の画素は粒にしない
    contrastToBackground: 1.5, // 周囲の平均の何倍以上明るければ粒にするか
    backgroundOffset: 0.04, // 上の判定に足す余裕(雲や霞を拾わないため)

    // ▼ 明るさ:粒の明るさ = 元の色 * (boostBase + 明るさ * boostByLuminance)
    boostBase: 0.45, // どの粒にもかかる基本の倍率
    boostByLuminance: 0.9, // 明るい粒ほど上乗せされる倍率

    // ▼ 大きさ:粒の大きさ = 画素の間隔 * (sizeBase + 明るさ * sizeByLuminance)
    sizeBase: 1.0,
    sizeByLuminance: 2.2,
    minPixelSize: 1.5, // 画面上での最小サイズ(px)。これより小さい粒は暗くして描く
    softness: 16, // 粒の輪郭のぼけ具合(大きいほど芯が小さくシャープ)

    // ▼ 高さ(読み込み時に一度だけ使う):明るい所ほど高く浮かせて奥行きを出す
    heightBase: 0.6, // 地面からの最低の高さ(1 ≒ 33m)
    heightByLuminance: 14, // 明るさの2乗に掛ける高さ
    heightJitter: 1.5, // ランダムなばらつき

    // ▼ またたき:明るさを (1 - depth) 〜 1 の間で揺らす
    twinkle: {
      depth: 0.56, // 揺れの深さ(0 でまたたかない。0.56 なら明るさ 44%〜100%)
      speedBase: 0.8, // 揺れの基本の速さ
      speedRange: 3.5, // 粒ごとの速さのばらつき
    },
  },

  // -------------------------------------------------------------------------
  // 雲(街明かりで下から照らされる)
  // -------------------------------------------------------------------------
  clouds: {
    baseColor: [0.004, 0.005, 0.009], // 照らされていない雲そのものの色(RGB)
    cityGlow: [0.3, 0.22, 0.16], // 街明かりの照り返しの強さ(RGB。赤を強めると暖色に)
    glowBlur: 7.0, // 照り返しに使う写真のぼかし量(大きいほど広くぼんやり)
    fadeNear: [30, 140], // カメラの近くの雲を消す距離の範囲(この間で徐々に現れる)
    // 雲の層(高さ y は 30 ≒ 1km)
    //   cover   … 雲量のしきい値。大きいほど雲が少ない(0.5〜0.8 程度)
    //   opacity … 濃さ
    //   wind    … 流れる速さと向き
    layers: [
      { y: 70, cover: 0.6, opacity: 0.45, wind: [0.0032, 0.0011], seed: 3.1 },
      {
        y: 150,
        cover: 0.66,
        opacity: 0.3,
        wind: [0.0045, -0.0007],
        seed: 17.4,
      },
    ],
  },

  // -------------------------------------------------------------------------
  // 空と星
  // -------------------------------------------------------------------------
  sky: {
    horizonLift: 1.6, // 地平線の明るさ(霧の色に対する倍率)
    horizonTint: [0.0, 0.004, 0.02], // 地平線に足す色味(RGB。青みの残光)
    zenith: [0.0, 0.0, 0.004], // 真上の空の色(RGB)
    starDensity: 0.9965, // 星の少なさ(1 に近いほど少ない。0.99 で多め)
    starBrightness: 0.8, // 星の明るさ
  },

  // -------------------------------------------------------------------------
  // 霧(遠くほど暗い青に溶け込む)
  // -------------------------------------------------------------------------
  fog: {
    color: [0.006, 0.01, 0.026], // 霧の色(RGB)。地平線の空の色にも使われる
    distance: 5200, // 霧が濃くなる目安の距離(小さいほど近くからかすむ。30 ≒ 1km)
  },

  // -------------------------------------------------------------------------
  // ブルーム(明るい光を周囲ににじませる画面全体の処理)
  // -------------------------------------------------------------------------
  bloom: {
    strength: 0.5, // にじみの強さ
    radius: 0.3, // にじみの広がり(0〜1)
    threshold: 0.4, // この明るさを超えた部分だけがにじむ(下げるほど多くがにじむ)
  },
};
